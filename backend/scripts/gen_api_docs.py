"""Generate docs/API.md (conventions + every endpoint) and docs/openapi.json from the FastAPI app.

    uv run python scripts/gen_api_docs.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from fastapi.routing import APIRoute  # noqa: E402

from app.main import create_app  # noqa: E402

INTRO = """# API reference

Interactive documentation (try requests in the browser): **`/api/docs`** · machine-readable: `/api/openapi.json`
(a copy is in `docs/openapi.json`). Generated by `backend/scripts/gen_api_docs.py`.

## Conventions
- Base path `/api/v1`. JSON in and out; UTF-8; timestamps in ISO 8601 UTC.
- Success: `{"data": …, "meta": {…}}` (`meta` for lists: `page`, `page_size`, `total`, `pages`).
- Error: `{"error": {"code": "VALIDATION_ERROR", "message": "…", "details": [{"field": "email", "message": "…"}]}}`.
- Authentication: `Authorization: Bearer <access token>` from `POST /auth/login` (15-minute tokens). The refresh
  token is an `HttpOnly; SameSite=Strict` cookie; `POST /auth/refresh` issues a new access token.
- Permissions are checked on every endpoint (`403 FORBIDDEN`); disabled modules answer `403 MODULE_DISABLED`.
- Rate limits answer `429` with a message; uploads use `multipart/form-data`.
- Real-time: Socket.IO at `/realtime` (WebSocket), authenticated with the access token.

## Endpoints
"""


def main() -> None:
    app = create_app()
    rows = []
    for r in app.routes:
        if isinstance(r, APIRoute) and r.include_in_schema:
            for m in sorted(r.methods):
                rows.append((r.tags[0] if r.tags else "Other", r.path, m, r.summary or r.name))
    rows.sort()
    out = [INTRO, f"{len(rows)} endpoints.", ""]
    tag = None
    for t, path, m, s in rows:
        if t != tag:
            out += ["", f"### {t}", "", "| Method | Path | Purpose |", "|---|---|---|"]
            tag = t
        out.append(f"| {m} | `{path}` | {s} |")
    docs = Path(__file__).resolve().parents[2] / "docs"
    (docs / "API.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (docs / "openapi.json").write_text(json.dumps(app.openapi(), indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote docs/API.md ({len(rows)} endpoints) and docs/openapi.json")


if __name__ == "__main__":
    main()
